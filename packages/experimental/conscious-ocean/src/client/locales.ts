export const packetLabels = {
  source: 'sourcePacket', neighborhood: 'neighborhoodPacket', region: 'regionPacket', global: 'globalPacket', context: 'contextPacket',
} as const satisfies Record<PacketLevel, ConsciousOceanKey>

const memoryTypeLabels = new Map<string, ConsciousOceanKey>([
  ['memory:fact', 'memoryFact'], ['memory:preference', 'memoryPreference'], ['memory:constraint', 'memoryConstraint'],
])

/** @param kind - Provider source kind. @returns The Memory kind key or the generic source key. */
export function sourceTypeLabel(kind: string | undefined): ConsciousOceanKey {
  return (kind === undefined ? undefined : memoryTypeLabels.get(kind)) ?? 'source'
}
