"""Generate TS command type from the shared JSON Schema; Core validates this schema."""
import json
from pathlib import Path
root = Path(__file__).resolve().parents[1]
schema = json.loads((root / "packages/protocol/command.schema.json").read_text())

def ts(spec):
    if "anyOf" in spec:
        return " | ".join(ts(s) for s in spec["anyOf"])
    if "$ref" in spec:
        return ts(schema["$defs"][spec["$ref"].split("/")[-1]])
    if "const" in spec:
        return json.dumps(spec["const"])
    if "enum" in spec:
        return " | ".join(json.dumps(v) for v in spec["enum"])
    if spec["type"] == "object":
        props = spec.get("properties", {})
        if not props:
            if isinstance(spec.get("additionalProperties"), dict):
                return "Record<string, " + ts(spec["additionalProperties"]) + ">"
            return "Record<string, never>"
        return "{ " + "; ".join(f'{key}{"" if key in spec.get("required", []) else "?"}: {ts(value)}'
                               for key, value in props.items()) + " }"
    if spec["type"] == "array":
        return "Array<" + ts(spec["items"]) + ">"
    return {"string": "string", "integer": "number", "boolean": "boolean", "null": "null"}[spec["type"]]

lines = ["// Generated by scripts/generate_protocol.py. Do not edit.", "export type Command ="]
for index, branch in enumerate(schema["allOf"]):
    kind = branch["if"]["properties"]["type"]["const"]
    props = schema["properties"] | {"type": {"const": kind}} | branch["then"]["properties"]
    required = schema["required"] + branch["then"]["required"]
    lines.append("  " + ts({"type": "object", "properties": props, "required": required})
                 + (";" if index == len(schema["allOf"]) - 1 else " |"))
(root / "packages/protocol/command.ts").write_text("\n".join(lines) + "\n", encoding="utf-8")
